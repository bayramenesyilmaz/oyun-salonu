export function makeViewmodel(id) {
  const g = new THREE.Group();
  const camo = new THREE.MeshLambertMaterial({ map: T.camo(), flatShading: true });
  const add = (a) => {
    const [w, h, d, c, x, y, z, rx = 0, ry = 0, rz = 0, kind] = a;
    const m = new THREE.Mesh(
      new THREE.BoxGeometry(w, h, d),
      c === 'camo' ? camo : kind === 'emit' ? new THREE.MeshBasicMaterial({ color: c }) : new THREE.MeshLambertMaterial({ color: c, flatShading: true }),
    );
    m.position.set(x, y, z);
    m.rotation.set(rx, ry, rz);
    g.add(m);
  };
  BODY[id].forEach(add);
  (id === 'pistol' ? HANDS.pistol : id === 'awp' ? HANDS.awp : HANDS.rifle).forEach(add);
  const muz = new THREE.Object3D();
  muz.position.set(0, 0.02, id === 'pistol' ? -0.28 : id === 'awp' ? -1.5 : -1.2);
  g.add(muz);
  g.userData.muzzle = muz;
  // nişan hizası (ADS): kırmızı nokta / dürbün merkezi
  g.userData.adsY = id === 'awp' ? 0.11 : id === 'pistol' ? 0.066 : id === 'ak' ? 0.1 : 0.135;
  g.userData.adsZ = id === 'awp' ? -0.575 : id === 'pistol' ? -0.24 : id === 'ak' ? -0.12 : -0.335;
  return g;
}
